"""Test the ML ranker on real factory layouts (KIT AGV data set).

    python scripts/evaluate_real_layouts.py

The model was trained only on simulated factories. This puts it in 14 real
factories from German industry: their real stations, real driving distances and
real transport routes (which source supplies which station, and how often). See
agv_brain/real_layouts.py for what is real and what is still simulated.

Every situation is labelled by the exact optimizer, the same way as in
scripts/evaluate.py. The main test drives at 1 m/s (a typical industrial AGV);
a speed check repeats it at other speeds.

Writes reports/real_layouts.md, reports/real_layouts.csv and
reports/real_layouts_accuracy.png.
"""

import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from agv_brain.models import load_settings  # noqa: E402
from agv_brain.ranker import DEFAULT_MODEL_PATH, PairwiseRanker  # noqa: E402
from agv_brain.real_layouts import (KIT_DIR, REAL_AGV_SPEED_CM_S, industry_layouts,  # noqa: E402
                                    real_context, real_scenario)
from evaluate import POLICY_LABELS, TARGET, policy_table, run, summarize  # noqa: E402

RULES = ["weighted_rules", "earliest_stockout", "nearest", "fifo"]


def evaluate_at(layouts, base, ranker, speed_cm_s, per_layout, seed, n_range):
    dfs = []
    for k, lay in enumerate(layouts):
        ctx = real_context(lay, base, speed_cm_s)
        df, _, _ = run(lambda rng: ctx, ranker, per_layout, seed + k, n_range, real_scenario)
        dfs.append(df.assign(layout=lay.name, speed_m_s=speed_cm_s / 100))
    return pd.concat(dfs, ignore_index=True)


def chart(per_layout, best_rule, out):
    from plot_style import ML, MUTED, TEXT_2, finish, plt

    names = [n.replace("Industry", "Factory ") for n in per_layout.index]
    x = np.arange(len(names))
    fig, ax = plt.subplots(figsize=(8, 3.8))
    ax.bar(x - 0.2, per_layout["ml"] * 100, 0.4, color=ML, label="ML ranker")
    ax.bar(x + 0.2, per_layout[best_rule] * 100, 0.4, color=MUTED, label=POLICY_LABELS[best_rule])
    ax.axhline(TARGET * 100, color=TEXT_2, linestyle=":", linewidth=1, label="80 % target")
    ax.set_xticks(x, names, rotation=45, ha="right")
    ax.set_ylim(0, 105)
    ax.set_ylabel("Chose the best delivery (%)")
    ax.grid(axis="x", visible=False)
    ax.set_title(f"Accuracy in {len(names)} real factories (KIT data set, AGV at 1 m/s)", pad=28)
    ax.legend(loc="lower left", bbox_to_anchor=(0, 1.0), ncol=3, fontsize=9)
    finish(fig, out / "real_layouts_accuracy.png")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--per-layout", type=int, default=100, help="situations per real factory")
    ap.add_argument("--speed-check", type=float, nargs="*", default=[0.5, 2.0],
                    help="other AGV speeds to check, m/s (none = skip)")
    ap.add_argument("--speed-check-per-layout", type=int, default=40)
    ap.add_argument("--seed", type=int, default=20261104)
    ap.add_argument("--min-n", type=int, default=2)
    ap.add_argument("--max-n", type=int, default=7)
    ap.add_argument("--data", type=Path, default=KIT_DIR)
    ap.add_argument("--model", type=Path, default=DEFAULT_MODEL_PATH)
    ap.add_argument("--out", type=Path, default=ROOT / "reports")
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    t0 = time.perf_counter()
    layouts = industry_layouts(args.data)
    if not layouts:
        sys.exit(f"no real layouts found in {args.data} (see data/external/kit_agv_layouts/README.md)")
    base = load_settings()
    ranker = PairwiseRanker.load(args.model)
    n_range = (args.min_n, args.max_n)

    df = evaluate_at(layouts, base, ranker, REAL_AGV_SPEED_CM_S, args.per_layout, args.seed, n_range)
    summary = summarize(df)
    acc = summary.loc["ml", "top1_accuracy"]
    best_rule = summary.loc[RULES, "top1_accuracy"].idxmax()
    per_layout = df[df.policy != "optimal"].groupby(["layout", "policy"]).top1.mean().unstack()

    checks = [(REAL_AGV_SPEED_CM_S / 100, df)]
    for k, v in enumerate(args.speed_check or []):
        checks.append((v, evaluate_at(layouts, base, ranker, v * 100, args.speed_check_per_layout,
                                      args.seed + 1000 * (k + 1), n_range)))
    checks.sort(key=lambda c: c[0])

    pd.concat([d for _, d in checks], ignore_index=True).to_csv(args.out / "real_layouts.csv", index=False)
    chart(per_layout, best_rule, args.out)

    lines = [
        "# Evaluation on real factory layouts",
        "",
        f"Generated by `python scripts/evaluate_real_layouts.py --per-layout {args.per_layout}`.",
        "",
        f"**AI accuracy in 14 real factories (top-1 vs exact optimizer): {acc:.1%} - target 80 %: "
        f"{'PASS' if acc >= TARGET else 'FAIL'}**",
        "",
        "## What was tested",
        "",
        "The model was trained only on simulated factories. Here it works in real ones: the "
        f"{len(layouts)} industry layouts of the KIT AGV data set (Sperling et al., *IEEE Access* 11, "
        "2023, CC BY 4.0) that have more than one transport route. The other 16 industry layouts are "
        "shuttles between two points, with nothing to choose.",
        "",
        "- **Real:** the stations, the driving distance between them (2-340 m), which source supplies "
        "which station, and how many trips per hour each route has (busy routes get requests more often).",
        "- **Still simulated, as in training:** stock left, usage rate, criticality and waiting time "
        "of each request, and where the car is. The data set is a plan, not a snapshot of one moment.",
        "- **Assumed:** the AGV drives at 1 m/s, a typical industrial speed, and takes 4 s to load or "
        "unload, like our car. Trip time = distance / speed; the data has no track drawing, so no "
        "junction turns.",
        "",
        f"{len(df) // df.policy.nunique()} situations "
        f"({args.per_layout} per factory), {args.min_n}-{args.max_n} requests each, every one "
        "labelled by the exact optimizer.",
        "",
        "## Results (AGV at 1 m/s)",
        "",
        *policy_table(summary),
        "",
    ]
    fifo_stop = summary.loc["fifo", "mean_line_stop_s"]
    if fifo_stop > 0:
        lines += [f"The ML ranker cuts line-stop time by {(1 - summary.loc['ml', 'mean_line_stop_s'] / fifo_stop):.0%} "
                  "compared with first come, first served. The distances are much longer than on our "
                  "track, so stop times are longer for every policy, the optimizer included.", ""]
    lines += ["## Each factory", "",
              f"| Factory | Stations | Routes | ML ranker | {POLICY_LABELS[best_rule]} |", "|---|---|---|---|---|"]
    for lay in layouts:
        r = per_layout.loc[lay.name]
        lines.append(f"| {lay.name} | {len(lay.stations)} | {len(lay.routes)} | {r['ml']:.0%} | {r[best_rule]:.0%} |")
    lines += ["", f"Each factory has {args.per_layout} situations, so one factory's figure can be off by "
              "several points by chance. The total above is the reliable number.", "",
              "## Speed check", "",
              "Trip times depend on the AGV speed, which the data set does not give. The test is "
              "repeated at other speeds:", "",
              "| AGV speed | Situations | ML ranker | Best simple rule |", "|---|---|---|---|"]
    for v, d in checks:
        s = summarize(d)
        rule = s.loc[RULES, "top1_accuracy"]
        lines.append(f"| {v:g} m/s | {len(d) // d.policy.nunique()} | {s.loc['ml', 'top1_accuracy']:.1%} | "
                     f"{rule.max():.1%} ({POLICY_LABELS[rule.idxmax()]}) |")
    lines += ["", "## Chart", "", "![Accuracy in each real factory](real_layouts_accuracy.png)", ""]
    (args.out / "real_layouts.md").write_text("\n".join(lines), encoding="utf-8")

    pd.set_option("display.width", 160)
    print(summary.round(3).to_string())
    print(f"\nML top-1 accuracy in {len(layouts)} real factories: {acc:.1%} (target {TARGET:.0%})")
    print(f"done in {time.perf_counter() - t0:.0f} s -> {args.out / 'real_layouts.md'}")


if __name__ == "__main__":
    main()
